import {
  Activity,
  Bed,
  Bell,
  Calendar,
  Check,
  ChevronDown,
  ClipboardList,
  Clock,
  Eye,
  EyeOff,
  FileText,
  FlaskConical,
  Heart,
  House,
  Image as ImageIcon,
  LayoutGrid,
  Lock,
  LogOut,
  Maximize2,
  Minimize2,
  Minus,
  PanelsTopLeft,
  Pill,
  Plus,
  Printer,
  Receipt,
  Search,
  ShieldCheck,
  TriangleAlert,
  User,
  Users,
  X,
  type LucideProps,
} from 'lucide-react';

const ICONS = {
  activity: Activity,
  bed: Bed,
  bell: Bell,
  calendar: Calendar,
  check: Check,
  chevronDown: ChevronDown,
  clipboard: ClipboardList,
  clock: Clock,
  eye: Eye,
  eyeOff: EyeOff,
  file: FileText,
  flask: FlaskConical,
  heart: Heart,
  home: House,
  image: ImageIcon,
  grid: LayoutGrid,
  lock: Lock,
  logout: LogOut,
  maximize: Maximize2,
  restore: Minimize2,
  minus: Minus,
  layout: PanelsTopLeft,
  pill: Pill,
  plus: Plus,
  printer: Printer,
  receipt: Receipt,
  search: Search,
  shield: ShieldCheck,
  alert: TriangleAlert,
  user: User,
  users: Users,
  x: X,
} as const;

export type IconName = keyof typeof ICONS;

/** Lucide icons (ISC), 2px stroke, imported per icon so the bundle stays small. Decorative by default. */
export function Icon({
  name,
  size = 20,
  ...props
}: { name: IconName; size?: number } & LucideProps) {
  const Cmp = ICONS[name];
  return <Cmp size={size} strokeWidth={2} aria-hidden="true" focusable="false" {...props} />;
}
