//! Generates `tokens.css` for the packaged startup page from the canonical hms_workspace design tokens
//! (`hms-desktop-design-system-integration`: never copy token values by hand). Only the tokens listed in `USED` are
//! emitted; the build fails if one disappears or holds a value that is unsafe to place in CSS.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

use serde_json::Value;

/// Default location in this workspace; override with `HMS_DESIGN_TOKENS` until hms_workspace publishes a versioned
/// token package.
const DEFAULT_TOKENS: &str = "../hms_workspace/web/.claude/skills/design-tokens/references/tokens.json";

const USED: &[&str] = &[
    "color.semantic.bg.canvas",
    "color.semantic.bg.surface",
    "color.semantic.border.subtle",
    "color.semantic.border.focus",
    "color.semantic.text.primary",
    "color.semantic.text.secondary",
    "color.semantic.text.muted",
    "color.semantic.text.on-action",
    "color.semantic.action.primary",
    "color.semantic.action.primary-hover",
    "color.semantic.status.danger-bg",
    "color.semantic.status.danger-fg",
    "color.semantic.status.warning-bg",
    "color.semantic.status.warning-fg",
    "color.semantic.status.info-bg",
    "color.semantic.status.info-fg",
    "radius.md",
    "radius.lg",
    "space.8",
    "space.12",
    "space.16",
    "space.24",
    "space.32",
    "size.control",
    "shadow.window",
    "font.family.base",
    "font.style.title-lg",
    "font.style.body",
    "font.style.caption",
];

fn main() {
    println!("cargo::rerun-if-env-changed=HMS_DESIGN_TOKENS");
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let path = env::var_os("HMS_DESIGN_TOKENS").map_or_else(|| manifest.join(DEFAULT_TOKENS), PathBuf::from);
    println!("cargo::rerun-if-changed={}", path.display());

    let text = fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("design tokens not found at {} ({e}); set HMS_DESIGN_TOKENS", path.display()));
    let root: Value = serde_json::from_str(&text).expect("design tokens are valid JSON");

    let mut css = format!(
        "/* Generated by build.rs from hms_workspace design tokens ({DEFAULT_TOKENS}). Do not edit. */\n:root {{\n"
    );
    for token in USED {
        let value = resolve(&root, token, 0);
        let name = token.replace('.', "-");
        match value {
            Value::String(s) => line(&mut css, &name, &safe(token, &s)),
            Value::Array(list) => {
                let fonts: Vec<String> = list
                    .iter()
                    .map(|f| {
                        let f = f.as_str().unwrap_or_else(|| panic!("{token}: font family is not a string"));
                        let f = safe(token, f);
                        if f.contains(' ') { format!("\"{f}\"") } else { f }
                    })
                    .collect();
                line(&mut css, &name, &fonts.join(", "));
            }
            Value::Object(style) => {
                for key in ["fontSize", "lineHeight", "fontWeight"] {
                    let v = style.get(key).unwrap_or_else(|| panic!("{token}: missing {key}"));
                    let v = match v {
                        Value::String(s) => safe(token, s),
                        Value::Number(n) => n.to_string(),
                        _ => panic!("{token}.{key}: unexpected value"),
                    };
                    line(&mut css, &format!("{name}-{}", kebab(key)), &v);
                }
            }
            other => panic!("{token}: unsupported token value {other}"),
        }
    }
    css.push_str("}\n");

    let out = PathBuf::from(env::var("OUT_DIR").unwrap()).join("tokens.css");
    fs::write(out, css).unwrap();
}

/// The `$value` of a token, following `{a.b.c}` references.
fn resolve(root: &Value, token: &str, depth: u8) -> Value {
    assert!(depth < 8, "{token}: reference chain too deep");
    let node = token
        .split('.')
        .try_fold(root, |n, key| n.get(key))
        .and_then(|n| n.get("$value"))
        .unwrap_or_else(|| panic!("design token {token} not found"));
    match node.as_str() {
        Some(s) if s.starts_with('{') && s.ends_with('}') => resolve(root, &s[1..s.len() - 1], depth + 1),
        _ => node.clone(),
    }
}

/// Token values go into CSS verbatim, so only plain value characters are accepted.
fn safe(token: &str, v: &str) -> String {
    let ok = !v.is_empty()
        && v.chars().all(|c| c.is_ascii_alphanumeric() || " #.,()-%+".contains(c))
        && !v.contains("url(")
        && !v.contains("expression(");
    assert!(ok, "{token}: value {v:?} is not a plain CSS value");
    v.to_owned()
}

fn kebab(s: &str) -> String {
    s.chars().flat_map(|c| if c.is_ascii_uppercase() { vec!['-', c.to_ascii_lowercase()] } else { vec![c] }).collect()
}

fn line(css: &mut String, name: &str, value: &str) {
    writeln!(css, "  --{name}: {value};").unwrap();
}
