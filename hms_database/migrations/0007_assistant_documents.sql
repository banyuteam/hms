-- 0007 assistant: metadata of uploaded documents and of AI readings (schema assistant, ADR-SVC-009 document
-- understanding; owner decisions D-1 to D-12 of 2026-11-09).
-- Owner: hms_database (definitions); writes: hms_services assistant module (hms_assistant_rw); reads: hms_services;
-- reporting reads the monthly usage view only.
-- Classification: confidential. Metadata only: the files live on the document volume (D-2), never in the database.
-- Not stored at all (D-7): the question, the AI answer, the document text, and the original file name (names such as
-- "<patient>_SEP.pdf" carry patient data); the visit number is stored as the link to the tagged visit.
-- Retention (hms_services purge job): files deleted from the volume after 7 days (purged_at set here); metadata and
-- readings kept 12 months.
-- Requires group role hms_assistant_rw (bootstrap, added for 0006). Online-safe: new objects only. Rollback: fix forward.

-- One uploaded file that passed the checks (content type, malware scan, conversion) and was stored on the volume.
CREATE TABLE assistant.documents (
    id                   uuid        NOT NULL DEFAULT uuidv7(),
    organization_id      uuid        NOT NULL,
    facility_id          uuid        NOT NULL,
    user_id              uuid        NOT NULL,
    visit_number         text        NOT NULL,
    uploaded_media_type  text        NOT NULL,
    stored_media_type    text        NOT NULL,
    size_bytes           bigint      NOT NULL,
    page_count           integer,
    sha256               bytea       NOT NULL,
    storage_key          text        NOT NULL,
    scan_engine          text        NOT NULL,
    created_at           timestamptz NOT NULL DEFAULT now(),
    expires_at           timestamptz NOT NULL,
    purged_at            timestamptz,
    CONSTRAINT pk_documents PRIMARY KEY (id),
    CONSTRAINT uq_documents_storage_key UNIQUE (storage_key),
    CONSTRAINT fk_documents_facility FOREIGN KEY (facility_id, organization_id)
        REFERENCES platform.facilities (id, organization_id),
    CONSTRAINT fk_documents_user FOREIGN KEY (user_id, organization_id)
        REFERENCES iam.users (id, organization_id),
    CONSTRAINT ck_documents_visit_number CHECK (visit_number ~ '^[0-9/]{1,17}$'),
    CONSTRAINT ck_documents_uploaded_media_type CHECK (uploaded_media_type IN (
        'image/jpeg', 'image/png', 'application/pdf',
        'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
        'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet')),
    -- Office files are stored as their PDF conversion; images and PDFs as uploaded (images re-encoded).
    CONSTRAINT ck_documents_stored_media_type CHECK (
        (uploaded_media_type IN ('image/jpeg', 'image/png') AND stored_media_type = uploaded_media_type)
        OR (uploaded_media_type NOT IN ('image/jpeg', 'image/png') AND stored_media_type = 'application/pdf')),
    CONSTRAINT ck_documents_size_bytes CHECK (size_bytes BETWEEN 1 AND 10485760),
    CONSTRAINT ck_documents_page_count CHECK (
        (stored_media_type = 'application/pdf' AND page_count BETWEEN 1 AND 50)
        OR (stored_media_type <> 'application/pdf' AND page_count IS NULL)),
    CONSTRAINT ck_documents_sha256 CHECK (octet_length(sha256) = 32),
    CONSTRAINT ck_documents_storage_key CHECK (
        storage_key ~ '^[0-9]{4}/[0-9]{2}/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'),
    CONSTRAINT ck_documents_scan_engine CHECK (length(btrim(scan_engine)) BETWEEN 1 AND 128),
    -- The file is kept at most 30 days whatever the runtime policy says (D-7 sets 7).
    CONSTRAINT ck_documents_expires_at CHECK (expires_at > created_at AND expires_at <= created_at + interval '30 days'),
    CONSTRAINT ck_documents_purged_at CHECK (purged_at IS NULL OR purged_at >= created_at)
);
COMMENT ON TABLE assistant.documents IS
    'Uploaded document stored on the document volume (metadata only, no file name, no content); file purged after expires_at';
COMMENT ON COLUMN assistant.documents.storage_key IS 'Path on the document volume, generated by hms-services (yyyy/mm/uuid)';
COMMENT ON COLUMN assistant.documents.scan_engine IS 'Malware scanner and signature version that passed the file';
COMMENT ON COLUMN assistant.documents.purged_at IS 'When the file was deleted from the volume; set once';
CREATE INDEX idx_documents_user_id_created_at ON assistant.documents (user_id, created_at);
CREATE INDEX idx_documents_expires_at_unpurged ON assistant.documents (expires_at) WHERE purged_at IS NULL;
CREATE INDEX idx_documents_created_at ON assistant.documents (created_at);

-- One AI reading of up to five documents about one visit. The question and the answer are not stored (D-7).
CREATE TABLE assistant.document_readings (
    id               uuid        NOT NULL DEFAULT uuidv7(),
    request_id       uuid        NOT NULL,
    organization_id  uuid        NOT NULL,
    facility_id      uuid        NOT NULL,
    user_id          uuid        NOT NULL,
    visit_number     text        NOT NULL,
    status           text        NOT NULL,
    model            text,
    bridge_version   text,
    input_tokens     integer     NOT NULL DEFAULT 0,
    output_tokens    integer     NOT NULL DEFAULT 0,
    duration_ms      integer     NOT NULL DEFAULT 0,
    created_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_document_readings PRIMARY KEY (id),
    CONSTRAINT uq_document_readings_request_id UNIQUE (request_id),
    CONSTRAINT fk_document_readings_facility FOREIGN KEY (facility_id, organization_id)
        REFERENCES platform.facilities (id, organization_id),
    CONSTRAINT fk_document_readings_user FOREIGN KEY (user_id, organization_id)
        REFERENCES iam.users (id, organization_id),
    CONSTRAINT ck_document_readings_visit_number CHECK (visit_number ~ '^[0-9/]{1,17}$'),
    -- answered/declined/unreadable come from the bridge; failed, unavailable and over_budget are decided by hms-services.
    CONSTRAINT ck_document_readings_status CHECK (status IN
        ('answered', 'declined', 'unreadable', 'failed', 'unavailable', 'over_budget')),
    CONSTRAINT ck_document_readings_model CHECK (model ~ '^[a-z0-9][a-z0-9._-]{0,63}$'),
    CONSTRAINT ck_document_readings_bridge_version CHECK (length(bridge_version) BETWEEN 1 AND 64),
    CONSTRAINT ck_document_readings_counts CHECK (input_tokens >= 0 AND output_tokens >= 0 AND duration_ms >= 0),
    -- A reading that reached the model names the model and the bridge.
    CONSTRAINT ck_document_readings_provenance CHECK (
        status NOT IN ('answered', 'declined', 'unreadable') OR (model IS NOT NULL AND bridge_version IS NOT NULL))
);
COMMENT ON TABLE assistant.document_readings IS
    'AI reading of uploaded documents: who, when, which visit, outcome, model and token counts; never the question or answer';
CREATE INDEX idx_document_readings_user_id_created_at ON assistant.document_readings (user_id, created_at);
CREATE INDEX idx_document_readings_facility_id_created_at ON assistant.document_readings (facility_id, created_at);
CREATE INDEX idx_document_readings_created_at ON assistant.document_readings (created_at);

-- Which documents a reading used. A document may be read more than once.
CREATE TABLE assistant.document_reading_files (
    reading_id   uuid NOT NULL,
    document_id  uuid NOT NULL,
    CONSTRAINT pk_document_reading_files PRIMARY KEY (reading_id, document_id),
    CONSTRAINT fk_document_reading_files_reading_id FOREIGN KEY (reading_id)
        REFERENCES assistant.document_readings (id) ON DELETE CASCADE,
    CONSTRAINT fk_document_reading_files_document_id FOREIGN KEY (document_id)
        REFERENCES assistant.documents (id)
);
COMMENT ON TABLE assistant.document_reading_files IS 'Documents used by a reading (metadata link only)';
CREATE INDEX idx_document_reading_files_document_id ON assistant.document_reading_files (document_id);

-- Only purged_at changes, once (column grants allow nothing else).
CREATE FUNCTION assistant.documents_guard_update() RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, pg_temp
AS $$
BEGIN
    IF OLD.purged_at IS NOT NULL THEN
        RAISE EXCEPTION 'assistant.documents row % is already purged', OLD.id;
    END IF;
    IF NEW.purged_at IS NULL THEN
        RAISE EXCEPTION 'assistant.documents row % can only be marked purged', OLD.id;
    END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER trg_documents_guard_update BEFORE UPDATE ON assistant.documents
    FOR EACH ROW EXECUTE FUNCTION assistant.documents_guard_update();

-- Cost and outcome monitoring per month and facility (D-12). No user ids. Operational counts, not about individuals,
-- so not suppressed.
CREATE VIEW assistant.document_usage_monthly AS
SELECT date_trunc('month', created_at)::date AS month,
       organization_id,
       facility_id,
       status,
       model,
       count(*) AS readings,
       sum(input_tokens) AS input_tokens,
       sum(output_tokens) AS output_tokens
FROM assistant.document_readings
GROUP BY 1, 2, 3, 4, 5;
COMMENT ON VIEW assistant.document_usage_monthly IS 'AI document readings per month, facility, outcome and model, with token sums';

GRANT SELECT, INSERT, DELETE ON assistant.documents TO hms_assistant_rw;
GRANT UPDATE (purged_at) ON assistant.documents TO hms_assistant_rw;
GRANT SELECT, INSERT, DELETE ON assistant.document_readings TO hms_assistant_rw;
GRANT SELECT, INSERT ON assistant.document_reading_files TO hms_assistant_rw;
GRANT SELECT ON assistant.document_usage_monthly TO hms_assistant_rw, hms_report_read;
